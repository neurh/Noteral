#!/usr/bin/env node
// Generates everything derived from the App API spec
// (frontend/src/sdk-host/spec.ts), so the SDK, the docs and the assistant's
// tools can never drift apart:
//
//   sdk/src/types.ts            copy of frontend/src/sdk-host/types.ts
//   sdk/src/api.generated.ts    typed `app.*` surface for plugins
//   docs/sdk/api-reference.md   every method, event and permission
//   docs/sdk/api.json           the same, machine-readable (for agents/tools)
//   docs/sdk/llms.txt           compact index for coding agents
//   docs/sdk/llms-full.txt      guides + reference in one file
//
// Run from the repository root:  node scripts/build-sdk.mjs
// `--check` fails (exit 1) when a generated file is out of date.
import { createRequire } from "node:module";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(path.join(root, "frontend/package.json"));
const esbuild = require("esbuild");
const check = process.argv.includes("--check");

// ── load the spec ───────────────────────────────────────────────────────────

const specOut = path.join(root, "node_modules/.cache/noteral-spec.mjs");
await mkdir(path.dirname(specOut), { recursive: true });
await esbuild.build({
  entryPoints: [path.join(root, "frontend/src/sdk-host/spec.ts")],
  outfile: specOut,
  bundle: true,
  format: "esm",
  platform: "node",
  logLevel: "error",
});
const spec = await import(`${pathToFileURL(specOut).href}?t=${Date.now()}`);
const { METHODS, EVENTS, PERMISSIONS, callersOf } = spec;
const { toTypeScript } = await importSchema();
const SDK_VERSION = await sdkVersion();

async function importSchema() {
  const out = path.join(root, "node_modules/.cache/noteral-schema.mjs");
  await esbuild.build({ entryPoints: [path.join(root, "frontend/src/sdk-host/schema.ts")], outfile: out, bundle: true, format: "esm", platform: "node", logLevel: "error" });
  return import(`${pathToFileURL(out).href}?t=${Date.now()}`);
}

async function sdkVersion() {
  const source = await readFile(path.join(root, "frontend/src/sdk-host/handlers.ts"), "utf8");
  return /SDK_VERSION = "([^"]+)"/.exec(source)?.[1] ?? "2.0.0";
}

const outputs = new Map();
const emit = (file, content) => outputs.set(path.join(root, file), content);

const pluginMethods = METHODS.filter((method) => callersOf(method).includes("plugin"));
const assistantMethods = METHODS.filter((method) => callersOf(method).includes("assistant"));
const namespaces = (methods) => Array.from(new Set(methods.map((method) => method.name.split(".")[0])));
const short = (method) => method.name.split(".").slice(1).join(".");
const hasRequired = (method) => (method.params.required ?? []).length > 0;
const hasParams = (method) => Object.keys(method.params.properties).length > 0 || method.params.additionalProperties;
const TIER_LABEL = { read: "Ask, Edit, Creator", content: "Edit, Creator", app: "Creator" };

// ── sdk/src/types.ts ────────────────────────────────────────────────────────

const typesSource = await readFile(path.join(root, "frontend/src/sdk-host/types.ts"), "utf8");
emit("sdk/src/types.ts", `// Generated by scripts/build-sdk.mjs from frontend/src/sdk-host/types.ts. Do not edit.\n${typesSource}`);
const typeNames = Array.from(typesSource.matchAll(/^export (?:interface|type) (\w+)/gm), (match) => match[1]);

// ── sdk/src/api.generated.ts ────────────────────────────────────────────────

function jsdoc(lines, indent) {
  const body = lines.flatMap((line) => String(line).split("\n")).map((line) => `${indent} *${line ? ` ${line}` : ""}`);
  return `${indent}/**\n${body.join("\n")}\n${indent} */`;
}

function methodDoc(method) {
  const lines = [method.summary];
  if (method.details) lines.push("", method.details);
  lines.push("", `Permission: ${method.permission ? `\`${method.permission}\`` : "none"}${method.confirm ? " · asks the user first" : ""}`);
  if (method.example) lines.push("", "@example", ...method.example.split("\n"));
  return lines;
}

function apiInterface() {
  const out = [
    "// Generated by scripts/build-sdk.mjs from frontend/src/sdk-host/spec.ts. Do not edit.",
    `import type { ${typeNames.join(", ")} } from "./types";`,
    "",
    `export const SDK_VERSION = ${JSON.stringify(SDK_VERSION)};`,
    "",
    `/** A permission a plugin can request in manifest.json. */`,
    `export type Permission = ${PERMISSIONS.map((item) => JSON.stringify(item.id)).join(" | ")};`,
    "",
    "/** Payload of each app event (`this.registerEvent(name, handler)`). */",
    "export interface NoteralEventMap {",
    ...EVENTS.map((event) => `  /** ${event.summary}${event.permission ? ` Needs \`${event.permission}\`.` : ""} */\n  ${JSON.stringify(event.name)}: ${event.payload};`),
    "}",
    "",
    "export type NoteralEventName = keyof NoteralEventMap;",
    "",
    "/**",
    " * The Noteral App API, as seen by plugins. Every method takes a single",
    " * params object and returns a promise. Calls a plugin lacks the permission",
    " * for reject with `NoteralError` code \"permission\".",
    " */",
    "export interface NoteralApp {",
  ];
  for (const namespace of namespaces(pluginMethods)) {
    out.push(`  ${namespace}: {`);
    for (const method of pluginMethods.filter((item) => item.name.startsWith(`${namespace}.`))) {
      out.push(jsdoc(methodDoc(method), "    "));
      const params = hasParams(method) ? `params${hasRequired(method) ? "" : "?"}: ${toTypeScript(method.params, "    ")}` : "params?: Record<string, never>";
      out.push(`    ${short(method)}(${params}): Promise<${method.returns}>;`);
    }
    out.push("  };");
  }
  out.push("}", "");
  return out.join("\n");
}
emit("sdk/src/api.generated.ts", apiInterface());

// ── docs/sdk/api.json ───────────────────────────────────────────────────────

const apiJson = {
  sdkVersion: SDK_VERSION,
  generatedFrom: "frontend/src/sdk-host/spec.ts",
  tiers: { read: "Ask mode and up", content: "Edit mode and up", app: "Creator mode only" },
  permissions: PERMISSIONS,
  events: EVENTS,
  methods: METHODS.map((method) => ({
    name: method.name,
    summary: method.summary,
    details: method.details,
    permission: method.permission,
    tier: method.tier,
    callers: callersOf(method),
    confirm: Boolean(method.confirm),
    params: method.params,
    returns: method.returns,
    example: method.example,
  })),
};
emit("docs/sdk/api.json", `${JSON.stringify(apiJson, null, 2)}\n`);

// ── docs/sdk/api-reference.md ───────────────────────────────────────────────

function paramsTable(method) {
  const keys = Object.keys(method.params.properties);
  if (!keys.length) return method.params.additionalProperties ? "Takes any key/value map.\n" : "No parameters.\n";
  const rows = keys.map((key) => {
    const schema = method.params.properties[key];
    const type = toTypeScript(schema).replace(/\s+/g, " ").replace(/\|/g, "\\|");
    const required = method.params.required?.includes(key) ? "yes" : "";
    const notes = [schema.description, schema.default !== undefined ? `Default \`${JSON.stringify(schema.default)}\`.` : ""].filter(Boolean).join(" ");
    return `| \`${key}\` | \`${type}\` | ${required} | ${notes.replace(/\|/g, "\\|")} |`;
  });
  return ["| Param | Type | Required | Notes |", "| --- | --- | --- | --- |", ...rows, ""].join("\n");
}

function referenceMarkdown() {
  const out = [
    "<!-- Generated by scripts/build-sdk.mjs from frontend/src/sdk-host/spec.ts. Do not edit. -->",
    `# App API reference (SDK ${SDK_VERSION})`,
    "",
    "Every method below is callable from plugins as `this.app.<namespace>.<method>(params)` and,",
    "where marked, by the in-app assistant as a tool named `<namespace>_<method>`.",
    "All methods take one params object and return a promise.",
    "",
    "- **Permission** — what a plugin must declare in `manifest.json` (`none` = always allowed).",
    "- **Assistant modes** — Ask reads, Edit also changes content, Creator can change the whole app.",
    "- **Asks first** — the user confirms before it runs.",
    "",
    "## Contents",
    "",
    ...namespaces(METHODS).map((namespace) => `- [\`${namespace}\`](#${namespace})`),
    "- [Events](#events)",
    "- [Permissions](#permissions)",
    "- [Types](#types)",
    "",
  ];
  for (const namespace of namespaces(METHODS)) {
    out.push(`## ${namespace}`, "");
    for (const method of METHODS.filter((item) => item.name.startsWith(`${namespace}.`))) {
      const callers = callersOf(method);
      out.push(`### \`${method.name}\``, "", method.summary, "");
      if (method.details) out.push(method.details, "");
      const facts = [
        `**Permission:** ${method.permission ? `\`${method.permission}\`` : "none"}`,
        `**Returns:** \`${method.returns}\``,
        `**Callers:** ${callers.map((caller) => (caller === "plugin" ? "plugins" : "assistant")).join(", ")}`,
      ];
      if (callers.includes("assistant")) facts.push(`**Assistant modes:** ${TIER_LABEL[method.tier]}`);
      if (method.confirm) facts.push("**Asks first**");
      out.push(facts.join(" · "), "", paramsTable(method));
      if (method.example) out.push("```ts", method.example, "```", "");
    }
  }
  out.push("## Events", "", "Subscribe with `this.registerEvent(name, handler)`. Events are only computed while someone listens.", "");
  out.push("| Event | Payload | Permission | When |", "| --- | --- | --- | --- |");
  for (const event of EVENTS) out.push(`| \`${event.name}\` | \`${event.payload.replace(/\|/g, "\\|")}\` | ${event.permission ? `\`${event.permission}\`` : "none"} | ${event.summary} |`);
  out.push("", "## Permissions", "", "| Permission | Risk | Grants |", "| --- | --- | --- |");
  for (const item of PERMISSIONS) out.push(`| \`${item.id}\` | ${item.risk} | **${item.title}.** ${item.description} |`);
  out.push("", "## Types", "", "Return types, as shipped in `@noteral/sdk` (`sdk/src/types.ts`).", "", "```ts", typesSource.replace(/^\/\*\*[\s\S]*?\*\/\n\n/, "").trim(), "```", "");
  return out.join("\n");
}
emit("docs/sdk/api-reference.md", referenceMarkdown());

// ── docs/sdk/llms.txt + llms-full.txt ───────────────────────────────────────

function signature(method) {
  const keys = Object.keys(method.params.properties);
  const args = keys.map((key) => `${key}${method.params.required?.includes(key) ? "" : "?"}`).join(", ");
  return `${method.name}({${args}}) → ${method.returns}`;
}

function llmsIndex() {
  const out = [
    "# Noteral plugin SDK",
    "",
    `> Noteral is a local-first notes app. Plugins are sandboxed iframes that call a versioned App API (SDK ${SDK_VERSION}) over postMessage. A plugin is a manifest.json + one bundled main.js (+ optional styles.css), published as a GitHub Release and listed in the community registry.`,
    "",
    "Rules for agents writing plugins:",
    "- Extend `Plugin`, put setup in `onload()`, and finish main.js with `register(MyPlugin)`. Use `this.addCommand`, `this.registerEvent`, `this.registerInterval` so cleanup is automatic.",
    "- Call the app only through `this.app.<namespace>.<method>({ ...params })`. There is no DOM access to the app, no Node, no fetch (use `app.network.request`).",
    "- Declare every permission the code needs in manifest.json `permissions`. A call without it rejects with code \"permission\".",
    "- Keep ids stable: manifest `id` is reverse-domain and never changes; `version` is semver and matches the release tag.",
    "- Bundle to a single IIFE (`esbuild src/main.ts --bundle --format=iife --outfile=main.js`). `@noteral/sdk` is provided at runtime; bundling it adds only a few lines.",
    "",
    "## Docs",
    "",
    "- [Plugin guide](../plugins/README.md): quick start, lifecycle, commands, panels, events, settings",
    "- [Manifest](../plugins/manifest.md): every manifest.json field",
    "- [Extending the interface](../plugins/ui.md): HTML views, sidebar tabs, status widgets, custom blocks, custom page types, Home, appearance layers, plugins.test",
    "- [Publishing](../plugins/publishing.md): GitHub Releases + community registry",
    "- [API reference](api-reference.md): every method, event, permission and type",
    "- [api.json](api.json): the same reference, machine-readable",
    "- [Assistant](../assistant.md): AI chat, providers, Ask/Edit/Creator modes, tools",
    "",
    "## Methods (plugin-callable)",
    "",
  ];
  for (const method of pluginMethods) out.push(`- ${signature(method)}${method.permission ? ` [${method.permission}]` : ""} — ${method.summary}`);
  out.push("", "## Events", "");
  for (const event of EVENTS) out.push(`- ${event.name}: ${event.payload} — ${event.summary}`);
  out.push("", "## Permissions", "");
  for (const item of PERMISSIONS) out.push(`- ${item.id} (${item.risk}): ${item.description}`);
  out.push("");
  return out.join("\n");
}
emit("docs/sdk/llms.txt", llmsIndex());

const guides = ["docs/plugins/README.md", "docs/plugins/manifest.md", "docs/plugins/ui.md", "docs/plugins/publishing.md", "docs/assistant.md"];
const guideText = [];
for (const file of guides) {
  try {
    guideText.push(`<!-- ${file} -->\n${(await readFile(path.join(root, file), "utf8")).trim()}`);
  } catch {
    // A guide that doesn't exist yet is skipped.
  }
}
emit("docs/sdk/llms-full.txt", [llmsIndex(), ...guideText, referenceMarkdown()].join("\n\n---\n\n"));

// ── assistant plugin guide ──────────────────────────────────────────────────
// The assistant's plugins.docs tool serves these sections, so it can look up the
// plugin guide (including plugin-only APIs it has no tools for) while it writes code.

{
  const sections = [];
  for (const [file, label] of [["docs/plugins/README.md", "guide"], ["docs/plugins/ui.md", "ui"], ["docs/plugins/manifest.md", "manifest"]]) {
    const text = (await readFile(path.join(root, file), "utf8")).replace(/\r\n/g, "\n");
    const parts = text.split(/^(?=## )/m);
    const intro = parts.shift().replace(/^# .*\n/, "").trim();
    if (intro) sections.push({ file: label, title: label === "guide" ? "Overview" : `${label}: overview`, text: intro });
    for (const part of parts) {
      const [heading, ...rest] = part.split("\n");
      sections.push({ file: label, title: heading.replace(/^##\s+/, "").replace(/`/g, "").trim(), text: rest.join("\n").trim() });
    }
  }
  // Type definitions by name (with their doc comments), for plugins.docs({ type }).
  const types = {};
  let pending = [];
  let current = null;
  for (const line of typesSource.split("\n")) {
    const start = /^export (?:interface|type) (\w+)/.exec(line);
    if (start) {
      current = start[1];
      types[current] = [...pending, line];
      pending = [];
      if (/;\s*$/.test(line)) current = null;
      continue;
    }
    if (current) {
      types[current].push(line);
      if (/^[}\]]/.test(line) || (/;\s*$/.test(line) && !/^\s/.test(line))) current = null;
      continue;
    }
    if (/^\/\*\*/.test(line) || (pending.length && /^\s*\*/.test(line))) pending.push(line);
    else pending = [];
  }
  const typeText = Object.fromEntries(Object.entries(types).map(([name, lines]) => [name, lines.join("\n").trim()]));
  emit(
    "frontend/src/assistant/generated/pluginGuide.ts",
    `// Generated by scripts/build-sdk.mjs from docs/plugins/*.md. Do not edit.\n` +
      `export interface GuideSection { file: string; title: string; text: string }\n\n` +
      `export const PLUGIN_GUIDE: GuideSection[] = ${JSON.stringify(sections, null, 1)};\n\n` +
      `/** Return and parameter types of the App API, by name. */\n` +
      `export const PLUGIN_TYPES: Record<string, string> = ${JSON.stringify(typeText, null, 1)};\n`,
  );
}

// ── publishing CLI ──────────────────────────────────────────────────────────
// sdk/cli/noteral-plugin.mjs carries the permission list between markers so it
// stays one self-contained file; plugin repos (and the starter) keep a copy.

{
  const cliFile = "sdk/cli/noteral-plugin.mjs";
  const cli = await readFile(path.join(root, cliFile), "utf8");
  const start = "// @generated permissions start\n";
  const end = "// @generated permissions end\n";
  const from = cli.indexOf(start);
  const to = cli.indexOf(end);
  if (from < 0 || to < from) throw new Error(`${cliFile}: @generated permissions markers are missing`);
  const perms = PERMISSIONS.map((p) => `  { id: ${JSON.stringify(p.id)}, title: ${JSON.stringify(p.title)}, risk: ${JSON.stringify(p.risk)} },`);
  const block = [`export const SDK_VERSION = ${JSON.stringify(SDK_VERSION)};`, "export const PERMISSIONS = [", ...perms, "];", ""].join("\n");
  const next = cli.slice(0, from + start.length) + block + cli.slice(to);
  emit(cliFile, next);
  emit("examples/starter/scripts/noteral-plugin.mjs", next);
}

// ── write or check ──────────────────────────────────────────────────────────

let stale = 0;
for (const [file, content] of outputs) {
  let current = null;
  try {
    current = await readFile(file, "utf8");
  } catch {
    // new file
  }
  if (current === content) continue;
  if (check) {
    console.error(`out of date: ${path.relative(root, file)}`);
    stale++;
    continue;
  }
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, content);
}
if (check && stale) {
  console.error("Run `node scripts/build-sdk.mjs` and commit the result.");
  process.exit(1);
}
console.log(`SDK ${SDK_VERSION}: ${pluginMethods.length} plugin methods, ${assistantMethods.length} assistant tools, ${EVENTS.length} events.`);
