#!/usr/bin/env node
// Builds the SDK runtime injected into plugin iframes, the catalog examples
// and the starter plugin (after regenerating the SDK types and docs with
// scripts/build-sdk.mjs). Run from the repository root:
//   node scripts/build-plugins.mjs
import { createRequire } from "node:module";
import { copyFile, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(path.join(root, "frontend/package.json"));
const esbuild = require("esbuild");

await import("./build-sdk.mjs");

async function bundle(entry, outfile, { format = "iife" } = {}) {
  await mkdir(path.dirname(outfile), { recursive: true });
  await esbuild.build({
    entryPoints: [entry],
    outfile,
    bundle: true,
    format,
    platform: "browser",
    target: ["es2020"],
    minify: true,
    legalComments: "none",
    alias: { "@noteral/sdk": path.join(root, "sdk/src/index.ts") },
  });
}

const sdkOut = path.join(root, "frontend/src/plugins/generated/sdkSource.ts");
await bundle(path.join(root, "sdk/src/runtime.ts"), "/tmp/noteral-sdk.js");
const sdkCode = await readFile("/tmp/noteral-sdk.js", "utf8");
await writeFile(
  sdkOut,
  `// Generated by scripts/build-plugins.mjs. Do not edit by hand.\nexport const SDK_SOURCE = ${JSON.stringify(sdkCode)};\n`,
);

// Examples: examples/<name>/src/main.ts → examples/<name>/main.js. The ones
// in CATALOG are also copied into the app's bundled catalog.
const EXAMPLES = ["reading-time", "meeting-notes", "starter"];
// Noteral ships no bundled plugins: the examples live in examples/ and the registry.
const CATALOG = /** @type {string[]} */ ([]);
const catalogDir = path.join(root, "internal/plugins/catalog");
const catalog = [];
for (const name of EXAMPLES) {
  const dir = path.join(root, "examples", name);
  const manifest = JSON.parse(await readFile(path.join(dir, "manifest.json"), "utf8"));
  await bundle(path.join(dir, "src/main.ts"), path.join(dir, manifest.entry));
  if (!CATALOG.includes(name)) continue;
  const target = path.join(catalogDir, "plugins", manifest.id);
  await rm(target, { recursive: true, force: true });
  await mkdir(target, { recursive: true });
  await copyFile(path.join(dir, "manifest.json"), path.join(target, "manifest.json"));
  await copyFile(path.join(dir, manifest.entry), path.join(target, manifest.entry));
  catalog.push(manifest);
}
await writeFile(path.join(catalogDir, "catalog.json"), `${JSON.stringify({ version: 1, plugins: catalog }, null, 2)}\n`);
console.log(`Built SDK runtime and ${EXAMPLES.length} examples (${CATALOG.length} in the bundled catalog).`);
