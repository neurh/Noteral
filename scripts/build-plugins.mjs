#!/usr/bin/env node
// Builds the SDK payload injected into plugin iframes, the two catalog examples,
// and the starter plugin. Run from the repository root:
//   node scripts/build-plugins.mjs
import { createRequire } from "node:module";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(path.join(root, "frontend/package.json"));
const esbuild = require("esbuild");

async function bundle(entry, outfile, { format = "iife" } = {}) {
  await mkdir(path.dirname(outfile), { recursive: true });
  await esbuild.build({
    entryPoints: [entry],
    outfile,
    bundle: true,
    format,
    platform: "browser",
    target: ["es2020"],
    minify: true,
    legalComments: "none",
    alias: { "@noteral/sdk": path.join(root, "sdk/src/index.ts") },
  });
}

const sdkOut = path.join(root, "frontend/src/plugins/generated/sdkSource.ts");
await bundle(path.join(root, "sdk/src/index.ts"), "/tmp/noteral-sdk.js");
const sdkCode = await readFile("/tmp/noteral-sdk.js", "utf8");
await writeFile(
  sdkOut,
  `// Generated by scripts/build-plugins.mjs. Do not edit by hand.\nexport const SDK_SOURCE = ${JSON.stringify(sdkCode)};\n`,
);

await bundle(
  path.join(root, "examples/reading-time/src/plugin.ts"),
  path.join(root, "internal/plugins/catalog/plugins/com.noteral.reading-time/plugin.js"),
);
await bundle(
  path.join(root, "examples/meeting-notes/src/plugin.ts"),
  path.join(root, "internal/plugins/catalog/plugins/com.noteral.meeting-notes/plugin.js"),
);
await bundle(
  path.join(root, "examples/starter/src/plugin.ts"),
  path.join(root, "examples/starter/plugin.js"),
);
console.log("Built SDK payload and plugin examples.");
